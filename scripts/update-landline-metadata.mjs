import { readFile, writeFile } from "node:fs/promises"

const [version, file] = process.argv.slice(2)
if (!/^v\d+\.\d+\.\d+$/.test(version) || !file) {
  throw new Error("Usage: node scripts/update-landline-metadata.mjs <version> <PhoneNumberMetadata.xml>")
}

const xml = await readFile(file, "utf8")
const japan = xml.match(/<territory id="JP"(?=\s|>)[\s\S]+?<\/territory>/)?.[0]
const fixedLine = japan?.match(/<fixedLine>([\s\S]+?)<\/fixedLine>/)?.[1]
const numberPattern = fixedLine?.match(/<nationalNumberPattern>([\s\S]+?)<\/nationalNumberPattern>/)?.[1]
if (!numberPattern || !fixedLine.includes('<possibleLengths national="9"')) {
  throw new Error("Expected a nine-digit JP fixed-line pattern")
}

const rules = []
for (const [, pattern, attributes, body] of japan.matchAll(
  /<numberFormat pattern="([^"]+)"([^>]*)>([\s\S]*?)<\/numberFormat>/g,
)) {
  if (!attributes.includes('nationalPrefixFormattingRule="$NP$FG"')) continue
  if (!body.includes("<format>$1-$2-$3</format>")) continue

  const groups = [...pattern.matchAll(/\(\\d(?:\{(\d+)\})?\)/g)]
  if (groups.length !== 3 || groups.map(([group]) => group).join("") !== pattern) continue
  const [areaCode, exchange, subscriber] = groups.map(([, length]) => Number(length ?? 1))
  if (areaCode + exchange !== 5 || subscriber !== 4) continue

  // libphonenumber uses the most detailed leading-digits rule and the first matching format.
  const leadingDigits = [...body.matchAll(/<leadingDigits>([\s\S]+?)<\/leadingDigits>/g)].at(-1)?.[1]
  if (!leadingDigits) throw new Error("Expected leading digits for a JP national format")
  rules.push([leadingDigits.replace(/\s/g, ""), areaCode + 1])
}

if (new Set(rules.map(([, length]) => length)).size !== 4) {
  throw new Error("Expected JP fixed-line formats with two- to five-digit domestic area codes")
}

const source = [
  "// Generated by scripts/update-landline-metadata.mjs.",
  "// Adapted from libphonenumber PhoneNumberMetadata.xml (JP fixed line and national formats).",
  "// Copyright (C) 2009 The Libphonenumber Authors. Apache-2.0.",
  "// See docs/LICENSE-libphonenumber.txt for the full license.",
  "// https://github.com/google/libphonenumber/blob/" + version + "/resources/PhoneNumberMetadata.xml",
  "",
  "export const landlineNumberPattern = new RegExp(" +
    JSON.stringify("^(?:" + numberPattern.replace(/\s/g, "") + ")$") + ")",
  "",
  "export const landlineAreaCodeRules: ReadonlyArray<readonly [RegExp, number]> = [",
  ...rules.map(([pattern, length]) =>
    "  [new RegExp(" + JSON.stringify("^(?:" + pattern + ")") + "), " + length + "],",
  ),
  "]",
  "",
].join("\n")

await writeFile(new URL("../src/landline-metadata.ts", import.meta.url), source)
